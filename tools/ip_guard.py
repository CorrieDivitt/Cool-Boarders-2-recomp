#!/usr/bin/env python3
"""IP guard: keep anything derived from the Cool Boarders 2 disc out of Git and releases.

Players supply their own legally obtained disc. This repository and its releases
contain only original code and tools. This script blocks, by path and by content:
disc images and extracted files, game data formats, translated (generated) game
C, compiled game executables, memory card saves, BIOS dumps and box art.

Modes
  --staged          files staged for commit (pre-commit hook)
  --range A..B      every file in the commits in a range (pre-push hook, CI)
  --tree            every tracked file at HEAD
  --history         every file in every commit
  --release PATH    a release folder or .zip (release audit)

Exit code 0 = clean, 1 = blocked, 2 = usage error.
Exceptions go in .ipguard-allow (one glob per line, each with a # reason);
.ipguard-release-allow adds exceptions that apply only to --release audits.
"""
import argparse, fnmatch, hashlib, io, json, os, re, subprocess, sys, zipfile

MAX_BYTES = 8 * 1024 * 1024          # anything bigger is suspicious in a source repo
SCAN_BYTES = 64 * 1024 * 1024        # content scan limit per file

BLOCK_DIRS = ["generated/", "disc/", "prepared_disc/", "saves/", "bios/", "cache/",
              "aot/", "build/", "build-*/", "overlay_captures*", "launcher_assets/img/"]
BLOCK_EXT = {
    # disc images and dumps
    ".bin", ".cue", ".iso", ".img", ".chd", ".pbp", ".ecm", ".mdf", ".mds", ".ccd",
    ".sub", ".cdi", ".nrg", ".toc", ".7z", ".rar",
    # PlayStation / Cool Boarders 2 data formats
    ".str", ".xa", ".vb", ".vh", ".vab", ".seq", ".sep", ".tim", ".tmd", ".pmd",
    ".fbd", ".da", ".dem", ".npc", ".nep",
    # saves and states
    ".mcd", ".mcr", ".mc", ".gme", ".srm", ".sav", ".state", ".sstate",
    # compiled output
    ".exe", ".dll", ".so", ".dylib", ".a", ".lib", ".obj", ".o", ".pdb",
}
# Boot-EXE style names: SCUS_943.58, SLUS_012.34, SCUS_943.58_full_00.c ...
NAME_RE = re.compile(r"(^|/)(SC|SL)[A-Z]{2}[_-]\d{3}\.\d{2}", re.I)
BOXART_RE = re.compile(r"(^|/)(boxart|cover|title_?screen|screenshot)[^/]*\.(png|jpe?g|tga|bmp|webp|gif)$", re.I)

SYNC = b"\x00" + b"\xff" * 10 + b"\x00"
CONTENT_RULES = [
    ("PS-X EXE header (PlayStation executable)", lambda b: b.startswith(b"PS-X EXE")),
    # Executables (PE "MZ", ELF) carry sync bytes as emulator constants; the
    # game-code markers below still apply to them.
    ("raw CD sector sync pattern (disc image)",
     lambda b: not b[:2] == b"MZ" and not b[:4] == b"\x7fELF"
               and (b.startswith(SYNC) or b.count(SYNC) >= 4)),
    ("ISO 9660 volume descriptor (disc image)",
     lambda b: b[0x8001:0x8006] == b"CD001" or b[16 * 2352 + 25:16 * 2352 + 30] == b"CD001"),
    ("PSXRecomp generated game C", lambda b: b"Generated by PSXRecomp" in b and b"func_800" in b),
    ("translated Cool Boarders 2 code (many func_800xxxxx symbols)",
     lambda b: len(re.findall(rb"func_800[1-4][0-9A-Fa-f]{4}", b[:SCAN_BYTES])) >= 25),
    ("Cool Boarders 2 build string", lambda b: b"(c)UEP SYSTEMS" in b),
    ("Sony VAB sound bank", lambda b: b[:4] == b"pBAV"),
    ("Sony SEQ music", lambda b: b[:4] == b"pQES"),
]
# Text that legitimately names these markers (this guard, its docs) is exempt from content rules.
SELF_EXEMPT = {"tools/ip_guard.py", "docs/LEGAL.md", "LEGAL.md", ".github/workflows/ip-guard.yml"}


def load_allow(root, release=False):
    """.ipguard-allow applies everywhere; .ipguard-release-allow only to --release audits."""
    globs = []
    names = [".ipguard-allow"] + ([".ipguard-release-allow"] if release else [])
    for name in names:
        p = os.path.join(root, name)
        if os.path.exists(p):
            for line in open(p, encoding="utf-8"):
                g = line.split("#", 1)[0].strip()
                if g:
                    globs.append(g)
    return globs


def known_seeds(root):
    """Known game function entry addresses (seeds/ghidra_funcs.txt: facts, not content)."""
    p = os.path.join(root, "seeds", "ghidra_funcs.txt")
    out = set()
    if os.path.exists(p):
        for line in open(p, encoding="utf-8", errors="replace"):
            line = line.strip()
            if line.lower().startswith("0x"):
                try:
                    out.add(int(line, 16).to_bytes(4, "little"))
                except ValueError:
                    pass
    return out


SEEDS = set()


def known_hashes(root):
    """SHA-256 digests of disc files recorded by setup (facts, not content)."""
    out = set()
    for name in ("disc_probe.json", "catalog_identity.json"):
        p = os.path.join(root, name)
        if os.path.exists(p):
            txt = open(p, encoding="utf-8", errors="replace").read()
            out.update(re.findall(r'"boot_exe_sha256"\s*:\s*"([0-9a-f]{64})"', txt))
    return out


def path_reason(path, release):
    p = path.replace("\\", "/")
    low = p.lower()
    for d in BLOCK_DIRS:
        pat = d.rstrip("/")
        if "/" in pat:
            if ("/" + low).find("/" + pat.lower() + "/") >= 0:
                return "inside blocked folder %s" % d
            continue
        parts = low.split("/")
        for i in range(len(parts) - (0 if d.endswith("*") else 1)):
            if fnmatch.fnmatch(parts[i], pat.lower()):
                return "inside blocked folder %s" % d
    ext = os.path.splitext(low)[1]
    if ext in BLOCK_EXT and not (release and ext in {".exe", ".dll", ".so", ".dylib"}):
        return "blocked file type %s" % ext
    if NAME_RE.search(p):
        return "named like a PlayStation boot executable"
    if BOXART_RE.search(p):
        return "box art / screenshot image"
    return None


# Third-party trademark images that framework submodules ship and that must not
# reach a release. Matched by SHA-256 (a fact about the file, not the file).
TRADEMARK_SHA256 = {
    "8e553dbee2753ed85fb81f6f56b5afba98c407d45b65e7e270d766a174b43b32":
        "PlayStation logo (recomp-ui brand_psx.tga); tools/kit_prune.py replaces it",
}


def content_reason(path, data, hashes):
    digest = hashlib.sha256(data).hexdigest()
    if digest in hashes:
        return "identical to the game's boot executable"
    if digest in TRADEMARK_SHA256:
        return "third-party trademark: " + TRADEMARK_SHA256[digest]
    # A compiled game embeds its dispatch table: nearly every known function
    # address appears as a 32-bit word. A setup host or framework tool does not.
    if SEEDS and b"\0" in data[:8192]:
        hits = sum(1 for w in SEEDS if w in data)
        if hits >= max(25, len(SEEDS) // 4):
            return "compiled game executable (contains %d of %d known game function addresses)" % (hits, len(SEEDS))
    if path.replace("\\", "/") in SELF_EXEMPT:
        return None
    for label, rule in CONTENT_RULES:
        try:
            if rule(data):
                return label
        except Exception:
            pass
    return None


def check(items, allow, hashes, release=False):
    """items: iterable of (display_path, size, read_fn)."""
    bad = []
    for path, size, read in items:
        if any(fnmatch.fnmatch(path, g) for g in allow):
            continue
        why = path_reason(path, release)
        if not why and size > MAX_BYTES and not release:
            why = "larger than %d MB" % (MAX_BYTES // (1024 * 1024))
        if not why:
            why = content_reason(path, read(), hashes)
        if why:
            bad.append((path, why))
    return bad


def git(*args, root):
    return subprocess.run(["git", "-C", root] + list(args), check=True,
                          stdout=subprocess.PIPE).stdout


def blob_items(root, entries):
    """entries: list of (path, mode, sha). Submodule gitlinks are skipped."""
    for path, mode, sha in entries:
        if mode == "160000":
            continue
        size = int(git("cat-file", "-s", sha, root=root))
        yield path, size, (lambda s=sha: git("cat-file", "blob", s, root=root)[:SCAN_BYTES])


def ls_tree(root, rev):
    out = []
    for line in git("ls-tree", "-r", "-z", rev, root=root).split(b"\0"):
        if not line:
            continue
        meta, path = line.split(b"\t", 1)
        mode, _typ, sha = meta.decode().split()
        out.append((path.decode("utf-8", "replace"), mode, sha.decode() if isinstance(sha, bytes) else sha))
    return out


def staged(root):
    out = []
    raw = git("diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR", root=root)
    names = [n.decode("utf-8", "replace") for n in raw.split(b"\0") if n]
    for n in names:
        line = git("ls-files", "-s", "--", n, root=root).decode().split("\n")[0]
        if not line:
            continue
        mode, sha, _stage = line.split("\t")[0].split()
        out.append((n, mode, sha))
    return out


def commits_in(root, spec):
    return [c for c in git("rev-list", *spec.split(), root=root).decode().split() if c]


def release_items(path):
    if zipfile.is_zipfile(path):
        z = zipfile.ZipFile(path)
        for info in z.infolist():
            if not info.is_dir():
                yield info.filename, info.file_size, (lambda i=info: z.open(i).read(SCAN_BYTES))
    else:
        for dp, _dn, fn in os.walk(path):
            for f in fn:
                full = os.path.join(dp, f)
                rel = os.path.relpath(full, path).replace("\\", "/")
                yield rel, os.path.getsize(full), (lambda p=full: open(p, "rb").read(SCAN_BYTES))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--staged", action="store_true")
    g.add_argument("--tree", action="store_true")
    g.add_argument("--history", action="store_true")
    g.add_argument("--range")
    g.add_argument("--release")
    ap.add_argument("--root", default=None)
    a = ap.parse_args()
    root = a.root or git("rev-parse", "--show-toplevel", root=os.getcwd()).decode().strip()
    allow, hashes = load_allow(root, release=bool(a.release)), known_hashes(root)
    SEEDS.update(known_seeds(root))

    if a.release:
        bad = check(release_items(a.release), allow, hashes, release=True)
        where = a.release
    elif a.staged:
        bad = check(blob_items(root, staged(root)), allow, hashes)
        where = "staged changes"
    else:
        revs = (["HEAD"] if a.tree else
                commits_in(root, "--all") if a.history else commits_in(root, a.range))
        seen, bad = set(), []
        for rev in revs:
            entries = [e for e in ls_tree(root, rev) if e[2] not in seen]
            seen.update(e[2] for e in entries)
            bad += [(f"{p} (in {rev[:8]})", w) for p, w in check(blob_items(root, entries), allow, hashes)]
        where = "HEAD" if a.tree else "history" if a.history else a.range

    if bad:
        print("IP guard: BLOCKED. These files look like they come from the game disc (%s):" % where)
        for p, w in bad:
            print("  - %s: %s" % (p, w))
        print("\nThis project ships nothing from the disc. Players supply their own legally obtained copy.")
        print("If a file is a genuine false positive, add it to .ipguard-allow with a # reason.")
        return 1
    print("IP guard: clean (%s)." % where)
    return 0


if __name__ == "__main__":
    sys.exit(main())
